/**
 * Portable README baseline: regenerate the budget table from the metrics
 * ledger instead of hand arithmetic.
 *
 * 口径 (methodology, stated so the numbers cannot be over-read):
 * - corpus: deterministic synthetic samples built from `test/fixtures/source-samples.mjs`
 *   — byte-identical on every machine and run, checked into the repo;
 * - pipeline: the real one, `slimContent` from `slim.js`, at the shipped defaults
 *   plus the budget tier under test — not a simulation of it;
 * - accounting: every sample is recorded through `metrics.js recordResult`
 *   (unchanged samples included), and the rate comes from `summarizeMetrics`,
 *   so the denominator is everything the model would have received;
 * - scope: these numbers describe this corpus and this pipeline version. They
 *   are not a savings promise for any other workload. Measuring your own
 *   transcripts stays with the explicit tools (`test/budget-swap.mjs`), which
 *   read private sessions and stay out of the default suite.
 *
 * Usage: node scripts/readme-baseline.mjs
 */

import { estimateTokens, resolveOptions, slimContent } from '../slim.js';
import { createMetricsState, recordResult, summarizeMetrics } from '../metrics.js';
import { asReadResult, syntheticDiff, syntheticJson, syntheticLog, syntheticSource } from '../test/fixtures/source-samples.mjs';

const PACKAGE_VERSION = '1.1.0';

/** Deterministic corpus: every content type the router knows, in a few size classes. */
function buildCorpus() {
  return [
    { id: 'code-s', toolName: 'bash', text: syntheticSource(120) },
    { id: 'code-m', toolName: 'bash', text: syntheticSource(400) },
    { id: 'code-l', toolName: 'bash', text: syntheticSource(1200) },
    { id: 'log-s', toolName: 'bash', text: syntheticLog(200) },
    { id: 'log-m', toolName: 'bash', text: syntheticLog(800) },
    { id: 'log-l', toolName: 'bash', text: syntheticLog(2000) },
    { id: 'json-s', toolName: 'bash', text: syntheticJson(80) },
    { id: 'json-m', toolName: 'bash', text: syntheticJson(400) },
    { id: 'diff-s', toolName: 'bash', text: syntheticDiff(30) },
    { id: 'diff-m', toolName: 'bash', text: syntheticDiff(120) },
    { id: 'read-m', toolName: 'read', text: asReadResult('src/app.ts', syntheticSource(600)) },
  ];
}

/** Run one sample through the real pipeline and record it on the ledger. */
function runSample(state, sample, options) {
  const blocks = [{ type: 'text', text: sample.text }];
  const beforeTokens = estimateTokens(sample.text);
  const result = slimContent(blocks, sample.toolName, options, false, { analysisIntent: false });
  const afterTokens = result === null
    ? beforeTokens
    : result.blocks.reduce((sum, block) => sum + (block.type === 'text' ? estimateTokens(block.text) : 0), 0);
  recordResult(state, {
    id: sample.id,
    mode: 'applied',
    beforeTokens,
    afterTokens,
    changed: result !== null,
    toolName: sample.toolName,
  });
  return { beforeTokens, afterTokens, changed: result !== null };
}

const TIERS = [
  [4000, 12000],
  [3000, 8000],
  [2000, 5000],
  [1500, 4000],
];

const corpus = buildCorpus();
const today = new Date().toISOString().slice(0, 10);

console.log('<!-- generated by scripts/readme-baseline.mjs — regenerate, do not hand-edit -->');
console.log(`<!-- 口径: 合成语料（test/fixtures，确定性）× 真实管线（slimContent）× metrics 账本（summarizeMetrics）; ${PACKAGE_VERSION}; ${today} -->`);
console.log(`<!-- corpus: ${corpus.length} samples, ${corpus.reduce((sum, sample) => sum + estimateTokens(sample.text), 0)} tokens total -->`);
console.log(`<!-- samples: ${corpus.map((sample) => `${sample.id}(${sample.toolName},${estimateTokens(sample.text)}t)`).join(', ')} -->`);
console.log('<!-- 语料刻意由远超预算的大型合成产物组成，压测的是内核；不对应任何真实会话的样本分布， -->');
console.log('<!-- 因此比率高于真实转写测量（旧行为下 2000/5000 档为 21.7%），两者不可比。真实测量用 test/budget-swap.mjs。 -->');
console.log('');

// Per-tier table: the savings rate over the full denominator, touched = changed samples.
console.log('| 预算（通用/read） | 节省率 | 触及样本 | 输入 token |');
console.log('|---|---:|---:|---:|');
for (const [genericBudget, readBudget] of TIERS) {
  const options = resolveOptions({ maxResultTokens: genericBudget, readMaxResultTokens: readBudget });
  const state = createMetricsState();
  let touched = 0;
  for (const sample of corpus) {
    const { changed } = runSample(state, sample, options);
    if (changed) touched += 1;
  }
  const summary = summarizeMetrics(state);
  console.log(
    `| ${genericBudget} / ${readBudget} | ${(summary.applied.savingsRate * 100).toFixed(1)}% | ${touched} / ${corpus.length} | ${summary.applied.inputTokens} |`,
  );
}
console.log('');

// Per-type table at the recommended tier, one ledger per type.
const RECOMMENDED = resolveOptions({ maxResultTokens: 2000, readMaxResultTokens: 5000 });
console.log(`<!-- recommended tier 2000 / 5000, by content type -->`);
console.log('| 内容类型 | 样本 | 输入 token | 节省 token | 节省率 |');
console.log('|---|---:|---:|---:|---:|');
for (const id of [...new Set(corpus.map((sample) => sample.id.split('-')[0]))]) {
  const samples = corpus.filter((sample) => sample.id.startsWith(`${id}-`));
  const state = createMetricsState();
  for (const sample of samples) runSample(state, sample, RECOMMENDED);
  const summary = summarizeMetrics(state);
  console.log(
    `| ${id} | ${samples.length} | ${summary.applied.inputTokens} | ${summary.applied.estimatedTokensSaved} | ${(summary.applied.savingsRate * 100).toFixed(1)}% |`,
  );
}
console.log('');
console.log('summary (recommended tier):');
const overall = createMetricsState();
for (const sample of corpus) runSample(overall, sample, RECOMMENDED);
console.log(JSON.stringify(summarizeMetrics(overall).applied, null, 2));
